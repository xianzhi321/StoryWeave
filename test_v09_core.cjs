'use strict';
const assert=require('node:assert/strict');
const C=require('./web/plot-core.js');
const a='第一段：钟楼下的信。',b='另一种走向：沈雾接过了信。';
const src={id:'chapter1',title:'第一章',text:a,history:[]};
const branch=C.createBranch({newId:'branch1',projectId:'project1',chapterId:'chapter1',title:'第二种选择',premise:'坦白',baseText:a,created:'2026-11-08T00:00:00Z'});
assert.equal(branch.baseText,a);assert.equal(branch.draft,a);
branch.draft=b;
assert(C.checkBranchConflict(branch,src).ok);
assert(!C.checkBranchConflict(branch,{...src,text:a+'新改动'}).ok);
assert.throws(()=>C.planPromotion(branch,{...src,text:a+'新改动'},'h1','now'),/已被修改/);
const after=C.planPromotion(branch,src,'snapshot0','2026-11-08T01:00:00Z');
assert.equal(src.text,a,'source must be immutable');assert.equal(after.text,b);assert.equal(after.history[0].text,a);
const p={id:'project1',chapters:[src]};
const roles=[{id:'r1',projectId:'project1'},{id:'r2',projectId:'project2'}];
const facts=[{id:'f1',projectId:'project1',truth:'真相',views:{}}];
assert.throws(()=>C.validateKnowledgeProposal({roleId:'r2',factId:'f1',status:'known'},p,roles,facts),/不属于当前作品/);
assert.throws(()=>C.validateKnowledgeProposal({roleId:'r1',factId:'f1',status:'suspected'},p,roles,facts),/必须写明/);
assert.throws(()=>C.validateKnowledgeProposal({roleId:'r1',factId:'f1',status:'known',sinceChapterId:'wrong'},p,roles,facts),/必须指向/);
const proposed=C.validateKnowledgeProposal({roleId:'r1',factId:'f1',status:'suspected',belief:'他以为那封信是假的',sinceChapterId:'chapter1'},p,roles,facts);
const knowledge={...proposed,targetStatus:proposed.status,status:'pending',projectId:'project1',expectedViewSignature:C.viewSignature(undefined)};
const newFacts=C.applyKnowledgeProposal(knowledge,facts);
assert.equal(newFacts[0].views.r1.status,'suspected');assert.equal(newFacts[0].views.r1.belief,'他以为那封信是假的');
assert.equal(facts[0].views.r1,undefined);
assert.throws(()=>C.applyKnowledgeProposal(knowledge,newFacts),/已在提案创建后改变/);
assert.throws(()=>C.applyKnowledgeProposal({...knowledge,status:'approved'},facts),/已处理/);
const correct=C.parseKnowledgeSuggestions(JSON.stringify({changes:[{roleId:'r1',factId:'f1',status:'suspected',belief:'这封信是假的',reason:'角色在草稿中表示了对来信的怀疑'},{roleId:'r2',factId:'f1',status:'known',reason:'他知道了真相并直接承认'},{roleId:'r1',factId:'f1',status:'known',reason:'重复建议应被忽略'}]}),p,roles,facts,'chapter1');
assert.equal(correct.length,1);assert.equal(correct[0].status,'suspected');
assert.throws(()=>C.parseKnowledgeSuggestions('abc',p,roles,facts,'chapter1'),/JSON/);
const m=C.editMetrics('他迟疑了一下。然后才转身离开。','他在门口停了几秒。走廊空无一人。');
assert(m.originalChars>0&&m.revisedChars>0);assert.throws(()=>C.editMetrics('一样','一样'),/相同/);
const skill=C.parseFeedbackReply(JSON.stringify({title:'隐藏心理解释',description:'把复杂的情绪落到可以感知的动作上，减少对动机的直接说明',category:'个性化写作',rules:['用一到两个具体动作代替情绪解释','保留能帮助读者推断人物意图的细节']}));
assert.equal(skill.rules.length,2);
assert.throws(()=>C.parseFeedbackReply('not json'),/JSON/);
assert.throws(()=>C.parseFeedbackReply(JSON.stringify({title:'不足',description:'短',rules:[]})),/缺少/);
console.log('PASS v0.9 core: immutable branches, history promotion, conflict blocking, project knowledge isolation, proposal atomicity, change metrics, strict skill schema');
