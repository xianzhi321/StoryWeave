'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync(__dirname+'/web/app.js','utf8');
const patch=fs.readFileSync(__dirname+'/web/v05.js','utf8');
const ctx={window:{},console,Date,JSON,Math,Intl,URL,AbortController,navigator:{},document:{addEventListener(){}},
 sessionStorage:{getItem:()=>null},clearTimeout:()=>{},setTimeout:()=>0};
vm.createContext(ctx);vm.runInContext(source,ctx);vm.runInContext(patch,ctx);
const run=code=>vm.runInContext(code,ctx);
run(`state=DEMO();state.canonFacts=[];state.version=5;chapterId=chapters()[0].id;`);
const selected=run('state.selected'),known=run('characters()[0].id'),suspect=run('characters()[1].id'),other=run('characters()[2].id');
const first=run('chapters()[0].id'),second=run('chapters()[1].id');
const sensitive='作者真相：林澈的父亲才是幕后主使';
const fact={id:'f1',projectId:selected,title:'绝不能透露的秘密',type:'人物秘密',truth:sensitive,views:{[known]:{status:'known',sinceChapterId:second},[suspect]:{status:'mistaken',belief:'沈雾相信幕后主使是警署',sinceChapterId:''}}};
run(`state.canonFacts.push(${JSON.stringify(fact)})`);
const c1=ctx.window.StoryWeaveCanon.roleBoundContext(known,first);
assert(!JSON.stringify(c1).includes(sensitive),'Future facts leaked into earlier chapter');
const c2=ctx.window.StoryWeaveCanon.roleBoundContext(known,second);
assert(JSON.stringify(c2).includes(sensitive),'Known fact missing after reveal');
const guess=ctx.window.StoryWeaveCanon.roleBoundContext(suspect,second);
assert(JSON.stringify(guess).includes('沈雾相信幕后主使是警署'));
assert(!JSON.stringify(guess).includes(sensitive),'Author-only truth leaked to mistaken character');
assert(!JSON.stringify(guess).includes('绝不能透露的秘密'),'Even author title must be hidden');
const blank=ctx.window.StoryWeaveCanon.roleBoundContext(other,second);
assert(!JSON.stringify(blank).includes(sensitive),'Third character unexpectedly received secret');
run(`state.settings.aiProvider='iridis';state.settings.localModel='my-phone-model';state.settings.localContextChars=6000`);
const restored=run('normalizeBackup(JSON.parse(JSON.stringify(state)))');
assert.equal(restored.canonFacts.length,1);assert.equal(restored.settings.aiProvider,'iridis');
assert.equal(restored.settings.localModel,'my-phone-model');
assert.equal(restored.version,5);
const tampered=JSON.parse(JSON.stringify(restored));
tampered.canonFacts.push({id:'other-project',projectId:'not-owned',title:'stray',truth:'stray'});
assert.equal(run('normalizeBackup('+JSON.stringify(tampered)+')').canonFacts.length,1);
const web=fs.readFileSync(__dirname+'/web/index.html','utf8');
assert(web.includes('v05.js'),'Browser must load V05 before bootstrap');
const android=fs.readFileSync(__dirname+'/android/app/src/main/assets/index.html','utf8');
assert(android.includes('v05.js'),'Android assets must load V05');
assert(fs.readFileSync(__dirname+'/web/v05.js','utf8').includes('const startWorkspace = () => bootstrap().catch(showStartupFailure);'),'Bootstrap start missing');
console.log('PASS v0.5: role knowledge boundaries, chapter-reveal checks, unknown views, privacy, portable backups, assets');
