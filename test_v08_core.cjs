'use strict';const assert=require('node:assert/strict');
const C=require('./web/distill-core.js');
const source=Array.from({length:1200},(_,i)=>`第${i+1}行，人物动作和细节铺垫让故事推进。\n`).join('');
const slices=C.planSamples(source,8,1100);
assert.equal(slices.length,8);assert(slices.every((s,i)=>s.index===i&&s.end<=source.length&&s.start>=0&&s.end>s.start));
assert(slices.every((s,i)=>!i||s.start>=slices[i-1].end),'overlapping samples');
assert.throws(()=>C.planSamples('短',3,900),/不足/);
assert.equal(C.fingerprint(source),C.fingerprint(source));
assert.notEqual(C.fingerprint(source),C.fingerprint(source+'改'));
const snippet=source.slice(slices[1].start,slices[1].end);
const quote=snippet.match(/人物动作和细节铺垫/)[0];
const obj={techniques:[{category:'场景细节',title:'以细节推动情节',description:'通过人物可察觉的细节组织线索推进，让读者自行形成判断',situation:'悬疑或日常场景',rules:['安排具体细节','让人物对细节采取行动'],quote,reason:'动作与细节被安排为推进因素'}]};
let res=C.verifyTechniqueReply(JSON.stringify(obj),slices[1],source);
assert.equal(res.valid.length,1);assert.equal(res.valid[0].evidence.start>=slices[1].start,true);
assert.equal(source.slice(res.valid[0].evidence.start,res.valid[0].evidence.end),quote);
obj.techniques[0].quote='原文中不存在的错误位置';
assert.throws(()=>C.verifyTechniqueReply(JSON.stringify(obj),slices[1],source),/未找到/);
obj.techniques[0].quote=quote;obj.techniques[0].category='自定义无效类别';
assert.throws(()=>C.verifyTechniqueReply(JSON.stringify(obj),slices[1],source),/未找到/);
assert.throws(()=>C.parseJSON('```js\nprocess.exit(1)\n```'),/JSON/);
obj.techniques[0].category='场景细节';
const two=C.verifyTechniqueReply(JSON.stringify(obj),slices[2],source).valid;
const aggregated=C.aggregate([...res.valid,...two],{id:'doc1',title:'测试参考文献'},()=>Math.random().toString());
assert.equal(aggregated.length,1);assert.equal(aggregated[0].sourceCoverage,2);
assert.equal(aggregated[0].confidence,'跨区段观察');
assert.equal(C.verifyRefs({id:'doc1',text:source},aggregated[0].evidenceRefs).filter(x=>x.valid).length,2);
assert.equal(C.verifyRefs({id:'different',text:source},aggregated[0].evidenceRefs).filter(x=>x.valid).length,0);
const md=C.portableSkillMarkdown(aggregated[0]);
assert(md.includes('操作规则'));assert(!md.includes(quote),'Evidence quotation leaked into export');
const other={...two[0],title:'用动作替代解释',rules:['写出动作','删掉解释']};
const grouped=C.aggregate([...res.valid,...two,other],{id:'doc1',title:'测试参考文献',text:source});
assert.equal(grouped.length,2,'Same-category techniques were conflated');
assert.equal(grouped[0].sourceCoverage,2,'Cross-section observations were not prioritized');
assert(!grouped[0].rules.includes(other.rules[0]),'Unrelated rules leaked into the technique');
assert.equal(C.techniqueKey({category:'场景细节',title:'以细节·推动情节'}),C.techniqueKey(res.valid[0]));
assert.throws(()=>C.verifyTechniqueReply(JSON.stringify(obj),slices[2],source,['人物对白']),/未找到/);
const chapters='目录\r\n第1章\r\n第2章\r\n第3章\r\n第4章\r\n\r\n第1章\r\n灯亮了。\r\n第2章\r\n他们离开。\r\n第3章\r\n风停了。\r\n第4章\r\n午后下雨。';
const opening=C.planOpeningSamples(chapters,900,line=>/^第\d章$/.test(line));
assert.deepEqual(opening.map(s=>chapters.slice(s.start,s.end).trim()),['灯亮了。','他们离开。','风停了。']);
assert.equal(C.planOpeningSamples('没有章节。'.repeat(50),50,()=>false).length,1);
const emoji='a😀b';
const bounded=C.planOpeningSamples(emoji,2,()=>false)[0];
assert.equal(emoji.slice(bounded.start,bounded.end),'a','Opening selection split a surrogate pair');
console.log('PASS v0.8 core: balanced whole-book samples, no overlap, strict JSON parsing, quoted evidence coordinates, invalid quote/category rejection, cross-sample aggregation, private evidence not included in skill export');
